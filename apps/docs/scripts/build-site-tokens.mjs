#!/usr/bin/env node

// Builds this site's tokens with the public Primitree packages. It solves the
// color primitives from tokens/theme.config.json, checks every theme and motion
// context, and stops on any finding before it writes the CSS the site imports.
// `--check` compares the outputs with the committed files and exits 1 on drift.
//
// This script calls the library because `primitree build` reads one flat file
// and writes no theme blocks. The CLI checks each flattened context as its own
// source, through tokens/primitree.config.ts.

import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  statSync,
  writeFileSync,
} from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  composeGraph,
  createSourceView,
  inspectToken,
  resolveView,
} from '@primitree/core'
import { createPolicy, evaluatePolicy } from '@primitree/core/policy'
import {
  applyResolver,
  createDTCGGraphFragment,
  emitCss,
  flattenTokens,
  listPermutations,
  typedCssValue,
} from '@primitree/dtcg'
import { siteTuning } from '../lib/tokens/signal-zones.ts'
import { siteLayers, siteOwnership } from '../lib/tokens/site-policy.ts'
import { solvePrimitives } from '../lib/tokens/solver.ts'
import { unwrap } from '../lib/tokens/unwrap.ts'

const docsRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..'
)
const tokensRoot = path.join(docsRoot, 'tokens')
const checkOnly = process.argv.includes('--check')

const readJson = file =>
  JSON.parse(readFileSync(path.join(tokensRoot, file), 'utf8'))
const pretty = value => `${JSON.stringify(value, null, 2)}\n`

function tokenFiles(directory = '') {
  return readdirSync(path.join(tokensRoot, directory)).flatMap(name => {
    const relative = directory === '' ? name : `${directory}/${name}`
    if (relative === 'generated') {
      return []
    }
    return statSync(path.join(tokensRoot, relative)).isDirectory()
      ? tokenFiles(relative)
      : name.endsWith('.tokens.json')
        ? [relative]
        : []
  })
}

/** Writes the solved colors into primitives.tokens.json and leaves every other
 * primitive as the file holds it. */
function primitivesWithSolvedColors(document, config) {
  const solved = solvePrimitives(config.hue, siteTuning)
  const { $type, $description } = document.primitives.color
  const color = { $type, $description }
  const notes = {
    neutral: 'Tinted toward the brand hue, chroma capped at 0.014.',
    brand:
      'Each step takes the most chroma its cap and sRGB allow at the luminance its number names. Changing the hue changes these values, never these names.',
    red: 'Locked at hue 27, so a failure always looks like a failure.',
    amber: 'Locked at hue 80.',
    blue: 'Locked at hue 260, for numbers in sample code.',
  }
  for (const [family, steps] of Object.entries(solved)) {
    color[family] = { $description: notes[family] }
    const ordered = Object.entries(steps).sort(
      ([a], [b]) => Number(b) - Number(a)
    )
    for (const [step, { L, C, h, hex }] of ordered) {
      color[family][step] = {
        $value: { colorSpace: 'oklch', components: [L, C, h], hex },
      }
    }
  }
  return {
    primitives: { ...document.primitives, color },
  }
}

const config = readJson('theme.config.json')
const files = Object.fromEntries(
  tokenFiles().map(file => [file, readJson(file)])
)
const solvedPrimitives = primitivesWithSolvedColors(
  files['primitives.tokens.json'],
  config
)
files['primitives.tokens.json'] = solvedPrimitives
const resolver = readJson('tokens.resolver.json')

// The rules live in primitree.config.ts, so the CLI and this build cannot disagree.
const policy = unwrap(
  createPolicy({
    id: 'site',
    viewId: 'site',
    layers: siteLayers,
    ownership: siteOwnership,
  }),
  'policy creation'
)

const banner =
  'Generated by apps/docs/scripts/build-site-tokens.mjs through emitCss from apps/docs/tokens. Do not edit. Set data-theme or data-motion on <html> to switch contexts.'

const contextName = contexts => Object.values(contexts).join('-')
const contexts = listPermutations(resolver)
const snapshots = new Map()
let failed = false

for (const context of contexts) {
  const document = applyResolver(files, resolver, context)
  const fragment = unwrap(
    createDTCGGraphFragment(document, { source: 'site' }),
    'graph creation'
  )
  const graph = unwrap(composeGraph([fragment]), 'graph composition')
  const view = unwrap(createSourceView(graph, { id: 'site' }), 'source view')
  unwrap(resolveView(graph, view), 'view resolution')
  const report = unwrap(
    evaluatePolicy({ graph, view }, policy),
    'policy evaluation'
  )
  const active = report.findings.filter(
    finding => finding.disposition === 'active'
  )
  for (const finding of active) {
    failed = true
    console.error(
      `${contextName(context)}: ${finding.ruleId} ${finding.path.join('.')}: ${finding.message}`
    )
  }
  snapshots.set(contextName(context), { document, graph, view })
}
if (failed) {
  process.exit(1)
}

/** Every token in one context: its layer, type, alias target, and CSS value. */
function readContext({ graph, view }) {
  const paths = new Map(
    view.tokens.map(token => [token.tokenId, token.path.join('.')])
  )
  return view.tokens.map(token => {
    const tokenPath = token.path.join('.')
    const inspection = unwrap(
      inspectToken({ graph, view }, { kind: 'path', path: token.path }),
      `inspection of ${tokenPath}`
    )
    const targetId = inspection.resolution.referenceChain[1]
    const target = targetId === undefined ? null : (paths.get(targetId) ?? null)
    const type = graph.tokens.find(item => item.id === token.tokenId)?.type
    return {
      path: tokenPath,
      layer: token.path[0],
      type,
      target,
      value: typedCssValue(inspection.resolution.value, type),
    }
  })
}

const descriptions = {}
for (const document of Object.values(files)) {
  for (const { path: tokenPath, token } of flattenTokens(document)) {
    if (typeof token.$description === 'string') {
      descriptions[tokenPath] = token.$description
    }
  }
}

const light = readContext(snapshots.get('light-full'))
const dark = readContext(snapshots.get('dark-full'))
const darkByPath = new Map(dark.map(token => [token.path, token]))
const graphData = {
  hue: config.hue,
  tokens: light.map(token => {
    const other = darkByPath.get(token.path)
    return {
      path: token.path,
      layer: token.layer,
      type: token.type,
      target: { light: token.target, dark: other?.target ?? null },
      value: { light: token.value, dark: other?.value ?? token.value },
      ...(descriptions[token.path] === undefined
        ? {}
        : { description: descriptions[token.path] }),
    }
  }),
}

const pathUnion = graphData.tokens
  .map(token => `  | '${token.path}'`)
  .sort()
  .join('\n')
const outputs = new Map([
  ['primitives.tokens.json', pretty(solvedPrimitives)],
  ['generated/tokens.css', emitCss(files, resolver, { banner })],
  ['generated/graph.json', pretty(graphData)],
  [
    'generated/token-path.ts',
    `// Generated by scripts/build-site-tokens.mjs. Do not edit.\nexport type TokenPath =\n${pathUnion}\n`,
  ],
  ...contexts.map(context => [
    `generated/resolved/${contextName(context)}.tokens.json`,
    pretty(snapshots.get(contextName(context)).document),
  ]),
])

let drifted = false
for (const [file, contents] of outputs) {
  const target = path.join(tokensRoot, file)
  if (checkOnly) {
    const current = existsSync(target) ? readFileSync(target, 'utf8') : null
    if (current !== contents) {
      drifted = true
      console.error(`${file} differs from what the tokens build to.`)
    }
  } else {
    mkdirSync(path.dirname(target), { recursive: true })
    writeFileSync(target, contents)
  }
}
if (drifted) {
  console.error('Run: node apps/docs/scripts/build-site-tokens.mjs')
  process.exit(1)
}

const count = layer =>
  graphData.tokens.filter(token => token.layer === layer).length
const edges = new Set(
  graphData.tokens.flatMap(token =>
    [token.target.light, token.target.dark]
      .filter(target => target !== null)
      .map(target => `${token.path}>${target}`)
  )
)
console.log(
  `Checked ${contexts.length} contexts: ${graphData.tokens.length} tokens (${count('primitives')} primitive, ${count('semantic')} semantic, ${count('component')} component), ${edges.size} references, 0 findings.`
)
